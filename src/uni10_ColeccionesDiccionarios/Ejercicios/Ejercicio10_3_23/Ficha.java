package uni10_ColeccionesDiccionarios.Ejercicios.Ejercicio10_3_23;

public class Ficha {

    private String nombre;
    private int valor;

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public int getValor() {
        return valor;
    }

    public void setValor(int valor) {
        this.valor = valor;
    }

    public Ficha(String nombre, int valor) {
        this.nombre = nombre;
        this.valor = valor;



    }
}
